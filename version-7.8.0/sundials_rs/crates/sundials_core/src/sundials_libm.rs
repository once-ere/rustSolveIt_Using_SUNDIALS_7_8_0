//! Pure-Rust elementary functions — the whole host-libm surface this port
//! touches, reimplemented so that **no numerical result depends on the C
//! library the binary happens to link against.**
//!
//! # Why this module exists
//!
//! Rust's `f64::sin`, `f64::cos`, `f64::exp`, `f64::ln`, … are documented as
//! having *unspecified precision*: they forward to the host libm. That makes
//! the printed output of an adaptive integrator a function of the host's
//! glibc **version**, not just of the algorithm — a one-ulp difference in
//! `sinh` forks the step-size trajectory. The sibling
//! `SUNDIALS_7_8_Rust_port_for_Linux` repository measured exactly that: three
//! ARKODE LSRK variants stop reproducing on glibc 2.44 because 2.44 changed
//! `sinh`, `cosh` and `acosh`.
//!
//! Routing every call through this module removes the host libm from the
//! numerical path entirely. The only remaining `f64` methods used are
//! `sqrt`, `mul_add`, `abs`, `ceil`, `round` and `copysign`, all of which
//! IEEE-754 specifies exactly and every Rust target implements identically.
//!
//! # What is implemented, and how faithful each one is
//!
//! Two different fidelity targets are in play, and the distinction is the
//! whole story of this module:
//!
//! | function | algorithm | relationship to glibc ≥ 2.28 on x86-64 |
//! |---|---|---|
//! | [`exp`], [`log`], [`pow`] | ARM optimized-routines (MIT), via musl | *the same source glibc ships* — expected and measured bit-identical |
//! | [`expm1`], [`log1p`], [`sinh`], [`cosh`], [`acosh`] | fdlibm / SunPro, via musl | the same lineage glibc ships — measured bit-identical |
//! | [`sin`], [`cos`], [`atan`], [`asin`], [`acos`] | double-double, written here | **correctly rounded**; glibc uses the LGPL IBM Accurate Mathematical Library, which is *not* correctly rounded (~0.51 ulp), so the two disagree on the last bit for a small measured fraction of inputs |
//!
//! The last row is a deliberate, licence-driven choice: glibc's `sin`/`cos`/
//! `atan`/`asin`/`acos` are LGPL-2.1 and cannot be copied into this
//! BSD-3-Clause tree, and no permissively licensed *bit-identical* equivalent
//! exists. Rather than ship a less accurate fdlibm clone that would disagree
//! with glibc *more* often, this module computes those five to ~2^-100
//! internal accuracy and rounds once — which is both the most accurate
//! option available and the closest achievable match to glibc.
//! `tools/libm_differential.sh` measures the residual disagreement rate
//! rather than asserting anything about it; see `LIBM.md`.
//!
//! # Provenance and licence
//!
//! * [`exp`], [`log`] and [`pow`] are translations of the ARM
//!   optimized-routines double-precision kernels, taken via musl's
//!   `src/math/{exp,log,pow}.c` and `{exp,log,pow}_data.c` — MIT,
//!   Copyright © 2018 Arm Limited. glibc ships the same algorithm as
//!   `sysdeps/ieee754/dbl-64/e_{exp,log,pow}.c`.
//! * [`expm1`], [`log1p`], [`sinh`], [`cosh`] and [`acosh`] are translations
//!   of the FreeBSD msun / SunPro fdlibm kernels, taken via musl's
//!   `src/math/{expm1,log1p,sinh,cosh,acosh}.c` — Copyright © 1993 Sun
//!   Microsystems, freely redistributable with notice preserved.
//! * The double-double core and the five inverse/forward trigonometric
//!   functions built on it are original to this repository. Their constant
//!   tables are generated by `tools/gen_libm_constants.py` from Taylor
//!   series in Python's stdlib `decimal`, and are reproducible by re-running
//!   that script.
//!
//! See `NOTICE` and `LIBM.md`.

