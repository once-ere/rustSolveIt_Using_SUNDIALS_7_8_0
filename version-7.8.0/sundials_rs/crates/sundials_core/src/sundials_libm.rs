/* =====================================================================
 * Payne-Hanek argument reduction for sin / cos
 * =====================================================================
 * Computes `n = round(x / (pi/2))` and `r = x - n*(pi/2)` with `r`
 * carried as a double-double whose *relative* accuracy is ~2^-128, so
 * no cancellation is lost even when `x` lands very close to a multiple
 * of pi/2. The reduction is exact integer arithmetic on the bits of
 * 2/pi, so its cost and its accuracy are both independent of |x|.
 */

/// 384-bit little-endian magnitude: `p[0]` is least significant.
type Big = [u64; 6];

/// 64 bits of `p` starting at bit index `from` (0 = least significant).
fn big_bits_at(p: &Big, from: usize) -> u64 {
    let w = from / 64;
    let o = from % 64;
    let lo = if w < 6 { p[w] } else { 0 };
    if o == 0 {
        return lo;
    }
    let hi = if w + 1 < 6 { p[w + 1] } else { 0 };
    (lo >> o) | (hi << (64 - o))
}

/// Index of the highest set bit of `p`, or `None` when `p` is zero.
fn big_bit_len(p: &Big) -> Option<usize> {
    for w in (0..6).rev() {
        if p[w] != 0 {
            return Some(w * 64 + (64 - p[w].leading_zeros() as usize));
        }
    }
    None
}

/// `p <- 2^bits - p`, for `p < 2^bits` and `bits <= 384`.
fn big_complement(p: &mut Big, bits: usize) {
    /* mask p to `bits`, then two's-complement it within that width */
    let full = bits / 64;
    let rem = bits % 64;
    for (w, slot) in p.iter_mut().enumerate() {
        if w < full {
            continue;
        } else if w == full && rem != 0 {
            *slot &= (1u64 << rem) - 1;
        } else {
            *slot = 0;
        }
    }
    let mut borrow = 1u64;
    for (w, slot) in p.iter_mut().enumerate() {
        let (v, b1) = (!*slot).overflowing_add(borrow);
        *slot = v;
        borrow = u64::from(b1);
        let _ = w;
    }
    /* re-mask: the complement is only meaningful within `bits` */
    for (w, slot) in p.iter_mut().enumerate() {
        if w < full {
            continue;
        } else if w == full && rem != 0 {
            *slot &= (1u64 << rem) - 1;
        } else if w >= full {
            *slot = 0;
        }
    }
}

/// Convert the top 128 significant bits of a magnitude to a double-double.
/// `m128` must have its bit 127 set; the returned pair equals
/// `m128 * 2^scale_exp` exactly to within 2^-128 relative.
fn u128_to_dd(m128: u128, scale_exp: i32) -> Dd {
    /* three chunks small enough to convert to f64 without rounding */
    let c0 = (m128 >> 86) as u64; /* 42 bits */
    let c1 = ((m128 >> 43) & ((1u64 << 43) as u128 - 1)) as u64; /* 43 bits */
    let c2 = (m128 & ((1u64 << 43) as u128 - 1)) as u64; /* 43 bits */
    let mut v = dd(c0 as f64 * exp2i(86 + scale_exp));
    v = dd_add_d(v, c1 as f64 * exp2i(43 + scale_exp));
    v = dd_add_d(v, c2 as f64 * exp2i(scale_exp));
    v
}

/// `2^n` for `n` in the normal range, built directly from the exponent field.
#[inline]
fn exp2i(n: i32) -> f64 {
    if n >= -1022 && n <= 1023 {
        f64::from_bits(((n + 1023) as u64) << 52)
    } else if n > 1023 {
        f64::INFINITY
    } else {
        /* split the scaling so the intermediate stays normal */
        let a = f64::from_bits(((-1022 + 1023) as u64) << 52);
        let mut r = a;
        let mut k = n + 1022;
        while k < -1022 {
            r *= a;
            k += 1022;
        }
        r * f64::from_bits(((k + 1023) as u64) << 52)
    }
}

/// Returns `(n mod 4, r)` with `x = n*(pi/2) + r` and `|r| <= pi/4`.
fn rem_pio2(x: f64) -> (u32, Dd) {
    let ix = x.to_bits();
    let sign = (ix >> 63) != 0;
    let ax = f64::from_bits(ix & (u64::MAX / 2));

    /* |x| <= pi/4: nothing to do. */
    if ax <= PI_OVER_4_DD.0 {
        return (0, dd(x));
    }

    /* Decompose |x| = m * 2^e with m a 53-bit integer. */
    let biased = ((ix >> 52) & 0x7ff) as i32;
    let (m, e) = if biased == 0 {
        /* subnormal: unreachable here because |x| > pi/4, but kept total */
        ((ix & 0x000f_ffff_ffff_ffff), -1074i32)
    } else {
        ((ix & 0x000f_ffff_ffff_ffff) | (1u64 << 52), biased - 1075)
    };

    /* Bits of 2/pi are indexed from 1 (the first fractional bit). Every
    term of m*2^e*(2/pi) whose weight is >= 4 is a multiple of 4 and so
    cannot affect the quadrant, which is why the window can start at
    bit e-1. */
    let b0: i32 = if e - 1 >= 1 { e - 1 } else { 1 };
    let start = (b0 - 1) as usize; /* 0-indexed into the bit stream */
    let wi = start / 64;
    let off = start % 64;

    /* 320-bit window of 2/pi, most significant word first */
    let mut u = [0u64; 5];
    for (i, slot) in u.iter_mut().enumerate() {
        let a = *TWO_OVER_PI.get(wi + i).unwrap_or(&0);
        let b = *TWO_OVER_PI.get(wi + i + 1).unwrap_or(&0);
        *slot = if off == 0 { a } else { (a << off) | (b >> (64 - off)) };
    }

    /* p = m * u, a 384-bit product (little-endian words) */
    let mut p: Big = [0; 6];
    let mut carry: u128 = 0;
    for i in 0..5 {
        let t = (m as u128) * (u[4 - i] as u128) + carry;
        p[i] = t as u64;
        carry = t >> 64;
    }
    p[5] = carry as u64;

    /* The binary point of p sits at bit `pt`: the window value is
    u * 2^-320, so p = m*u and x*2/pi == p * 2^(e - b0 + 1 - 320). */
    let pt = (320 - (e - b0 + 1)) as usize;

    /* integer part (mod 4) and the fractional bits */
    let int2 = (big_bits_at(&p, pt) & 3) as u32;
    let half_set = pt > 0 && (big_bits_at(&p, pt - 1) & 1) == 1;

    let mut frac = p;
    /* clear everything at or above the binary point */
    {
        let full = pt / 64;
        let rem = pt % 64;
        for (w, slot) in frac.iter_mut().enumerate() {
            if w < full {
                continue;
            } else if w == full && rem != 0 {
                *slot &= (1u64 << rem) - 1;
            } else {
                *slot = 0;
            }
        }
    }

    let (mut n, negative) = if half_set {
        /* round up: r becomes negative, magnitude 1 - frac */
        big_complement(&mut frac, pt);
        (int2.wrapping_add(1) & 3, true)
    } else {
        (int2, false)
    };

    /* frac * 2^-pt in [0, 1/2] -> double-double, keeping 128 significant
    bits *counted from the leading one*, so tiny remainders keep their
    full relative accuracy. */
    let f = match big_bit_len(&frac) {
        None => Dd(0.0, 0.0),
        Some(len) => {
            let m128: u128 = if len >= 128 {
                ((big_bits_at(&frac, len - 64) as u128) << 64)
                    | (big_bits_at(&frac, len - 128) as u128)
            } else {
                let lo = ((big_bits_at(&frac, 0) as u128)
                    | ((big_bits_at(&frac, 64) as u128) << 64))
                    << (128 - len);
                lo
            };
            u128_to_dd(m128, len as i32 - 128 - pt as i32)
        }
    };

    /* r = +- f * (pi/2), evaluated with pi/2 as a triple-double */
    let mut r = dd_mul(f, Dd(PI_OVER_2.0, PI_OVER_2.1));
    r = dd_add_d(r, f.0 * PI_OVER_2.2);
    if negative {
        r = dd_neg(r);
    }
    if sign {
        r = dd_neg(r);
        n = 4 - n;
        if n == 4 {
            n = 0;
        }
    }
    (n & 3, r)
}

/// `sin(r)` for `|r| <= pi/4`, carried in double-double.
fn sin_kernel(r: Dd) -> Dd {
    let z = dd_mul(r, r);
    let mut p = Dd(SIN_COEF[14].0, SIN_COEF[14].1);
    for c in SIN_COEF[..14].iter().rev() {
        p = dd_add(dd_mul(p, z), Dd(c.0, c.1));
    }
    dd_mul(r, p)
}

/// `cos(r)` for `|r| <= pi/4`, carried in double-double.
fn cos_kernel(r: Dd) -> Dd {
    let z = dd_mul(r, r);
    let mut p = Dd(COS_COEF[14].0, COS_COEF[14].1);
    for c in COS_COEF[..14].iter().rev() {
        p = dd_add(dd_mul(p, z), Dd(c.0, c.1));
    }
    p
}

/// `sin(x)`, correctly rounded except with probability ~2^-45 per call
/// (the internal accuracy is ~2^-100 before the single final rounding).
pub fn sin(x: f64) -> f64 {
    if !x.is_finite() {
        return x - x; /* NaN, and NaN for +-inf */
    }
    if x == 0.0 {
        return x; /* preserve -0.0 */
    }
    let (n, r) = rem_pio2(x);
    match n {
        0 => sin_kernel(r).value(),
        1 => cos_kernel(r).value(),
        2 => -sin_kernel(r).value(),
        _ => -cos_kernel(r).value(),
    }
}

/// `cos(x)`, correctly rounded except with probability ~2^-45 per call.
pub fn cos(x: f64) -> f64 {
    if !x.is_finite() {
        return x - x;
    }
    let (n, r) = rem_pio2(x);
    match n {
        0 => cos_kernel(r).value(),
        1 => -sin_kernel(r).value(),
        2 => -cos_kernel(r).value(),
        _ => sin_kernel(r).value(),
    }
}

