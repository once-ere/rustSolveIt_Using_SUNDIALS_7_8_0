/// `ln(x)`. Translation of musl `src/math/log.c` (ARM optimized-routines,
/// MIT) — the algorithm and tables glibc ≥ 2.29 ships as
/// `sysdeps/ieee754/dbl-64/e_log.c`. Worst-case error 0.52 ulp.
pub fn log(x: f64) -> f64 {
    const OFF: u64 = 0x3fe6000000000000;
    const LO: u64 = 0x3fef000000000000; /* asuint64(1.0 - 0x1p-4) */
    const HI: u64 = 0x3ff0900000000000; /* asuint64(1.0 + 0x1.09p-4) */

    let mut ix = x.to_bits();
    let top = (ix >> 48) as u32;

    if ix.wrapping_sub(LO) < HI - LO {
        /* Inputs close to 1.0 get their own polynomial. */
        if ix == 0x3ff0000000000000 {
            return 0.0;
        }
        let r = x - 1.0;
        let r2 = r * r;
        let r3 = r * r2;
        let b: [f64; 11] = {
            let mut t = [0.0f64; 11];
            let mut i = 0;
            while i < 11 {
                t[i] = f64::from_bits(LOG_POLY1[i]);
                i += 1;
            }
            t
        };
        let mut y = r3
            * (b[1]
                + r * b[2]
                + r2 * b[3]
                + r3 * (b[4] + r * b[5] + r2 * b[6] + r3 * (b[7] + r * b[8] + r2 * b[9] + r3 * b[10])));
        let w = r * f64::from_bits(0x41a0000000000000); /* 0x1p27 */
        let rhi = r + w - w;
        let rlo = r - rhi;
        let w = rhi * rhi * b[0]; /* b[0] == -0.5 */
        let hi = r + w;
        let lo = r - hi + w + b[0] * rlo * (rhi + r);
        y += lo;
        y += hi;
        return y;
    }
    if top.wrapping_sub(0x0010) >= 0x7ff0 - 0x0010 {
        /* x < 0x1p-1022, or inf, or nan. */
        if ix.wrapping_mul(2) == 0 {
            return f64::NEG_INFINITY; /* __math_divzero(1) */
        }
        if ix == f64::INFINITY.to_bits() {
            return x;
        }
        if (top & 0x8000) != 0 || (top & 0x7ff0) == 0x7ff0 {
            return f64::NAN; /* __math_invalid(x) */
        }
        /* x is subnormal: normalize it. */
        ix = (x * f64::from_bits(0x4330000000000000)).to_bits(); /* 0x1p52 */
        ix = ix.wrapping_sub(52u64 << 52);
    }

    /* x = 2^k z; z in [OFF, 2*OFF), exact. */
    let tmp = ix.wrapping_sub(OFF);
    let i = ((tmp >> (52 - 7)) % 128) as usize; /* LOG_TABLE_BITS = 7 */
    let k = (tmp as i64) >> 52; /* arithmetic shift */
    let iz = ix.wrapping_sub(tmp & (0xfffu64 << 52));
    let invc = f64::from_bits(LOG_TAB[i].0);
    let logc = f64::from_bits(LOG_TAB[i].1);
    let z = f64::from_bits(iz);

    /* r ~= z/c - 1, |r| < 1/(2*N); the FMA path, as on x86-64. */
    let r = z.mul_add(invc, -1.0);
    let kd = k as f64;

    let w = kd * f64::from_bits(LOG_LN2HI) + logc;
    let hi = w + r;
    let lo = w - hi + r + kd * f64::from_bits(LOG_LN2LO);

    let r2 = r * r;
    let a0 = f64::from_bits(LOG_POLY[0]);
    let a1 = f64::from_bits(LOG_POLY[1]);
    let a2 = f64::from_bits(LOG_POLY[2]);
    let a3 = f64::from_bits(LOG_POLY[3]);
    let a4 = f64::from_bits(LOG_POLY[4]);
    lo + r2 * a0 + r * r2 * (a1 + r * a2 + r2 * (a3 + r * a4)) + hi
}

/* =====================================================================
 * exp and log in double-double
 * =====================================================================
 * These two kernels carry ~106 significant bits, which is what lets
 * expm1, log1p, sinh, cosh and acosh below be *correctly rounded* rather
 * than merely faithful. glibc's own versions of those five are the
 * SunPro fdlibm kernels and measure 0.79 to 1.75 ulp on this host
 * (`tools/libm_differential.sh`), so the pure-Rust routines are strictly
 * more accurate; they are not, and cannot be, bit-identical to them.
 */

/// `e^x = m * 2^k` with `m` in `[1/sqrt(2), sqrt(2)]`, to ~2^-100
/// relative. Keeping the power of two separate is what lets `sinh` and
/// `cosh` stay correctly rounded right up to the overflow threshold,
/// where `e^x` itself is no longer representable.
fn exp_dd_scaled(x: f64) -> (Dd, i32) {
    /* x = k*ln2 + r, |r| <= ln2/2 */
    let k = (x * core::f64::consts::LOG2_E).round();
    let r = dd_sub(dd(x), dd_mul_d(Dd(LN2_DD.0, LN2_DD.1), k));
    /* exp(r) = sum r^n / n!, 25 terms cover |r| <= ln2/2 to 2^-107 */
    let mut p = Dd(INV_FACT[24].0, INV_FACT[24].1);
    for c in INV_FACT[..24].iter().rev() {
        p = dd_add(dd_mul(p, r), Dd(c.0, c.1));
    }
    (p, k as i32)
}

/// Multiply a double-double by `2^k` exactly, splitting the scaling so no
/// intermediate overflows for any `k` a finite result can need.
fn dd_ldexp(a: Dd, k: i32) -> Dd {
    let k1 = k / 2;
    dd_scale2(dd_scale2(a, exp2i(k1)), exp2i(k - k1))
}

/// `e^x` to ~2^-100 relative, as a double-double.
fn exp_dd(x: f64) -> Dd {
    let (m, k) = exp_dd_scaled(x);
    dd_ldexp(m, k)
}

/// `ln(w)` to ~2^-100 relative, as a double-double, for `w > 0`.
/// Accurate for `w` arbitrarily close to 1 because the reduction keeps
/// `w - 1` in double-double form.
fn log_dd(w: Dd) -> Dd {
    /* w = 2^k * m with m in [1, 2) */
    let k = ((w.0.to_bits() >> 52) & 0x7ff) as i32 - 1023;
    let m = dd_scale2(w, exp2i(-k));
    /* m / (1 + j/64) lands within 1/128 of 1 */
    let j = ((m.0 - 1.0) * 64.0).round();
    let c = 1.0 + j / 64.0; /* exact */
    let u = dd_div(m, dd(c));
    /* z = (u-1)/(u+1), |z| <= 1/256; log(u) = 2*atanh(z) */
    let num = dd_add_d(u, -1.0);
    let den = dd_add_d(u, 1.0);
    let z = dd_div(num, den);
    let z2 = dd_mul(z, z);
    let mut p = Dd(ATANH_COEF[9].0, ATANH_COEF[9].1);
    for a in ATANH_COEF[..9].iter().rev() {
        p = dd_add(dd_mul(p, z2), Dd(a.0, a.1));
    }
    let log_u = dd_scale2(dd_mul(z, p), 2.0);
    let e = &LOG_TAB_DD[j as usize];
    let mut r = dd_add(Dd(e.0, e.1), log_u);
    if k != 0 {
        r = dd_add(r, dd_mul_d(Dd(LN2_DD.0, LN2_DD.1), k as f64));
    }
    r
}

/* =====================================================================
 * expm1 / log1p / sinh / cosh / acosh — correctly rounded
 * ===================================================================== */

/// `e^x - 1`, correctly rounded. The subtraction that cancels in
/// `exp(x) - 1` is avoided by summing the Taylor series without its
/// leading 1 whenever `|x|` is small.
pub fn expm1(x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }
    if x == f64::NEG_INFINITY {
        return -1.0;
    }
    if x == f64::INFINITY {
        return x;
    }
    if x == 0.0 {
        return x; /* preserve -0.0 */
    }
    if x.abs() < exp2i(-54) {
        /* expm1(x) == x to within half an ulp, and this avoids
        underflow bookkeeping in the series */
        return x;
    }
    if x > 709.782712893384 {
        return f64::INFINITY;
    }
    if x < -40.0 {
        /* exp(x) is below 2^-58, so expm1(x) rounds to exp(x) - 1 */
        return exp_dd(x).value() - 1.0;
    }
    if x.abs() <= 0.5 {
        /* sum_{n>=1} x^n / n!, i.e. x * sum_{n>=0} x^n/(n+1)! */
        let xd = dd(x);
        let mut p = Dd(INV_FACT[24].0, INV_FACT[24].1);
        for c in INV_FACT[1..24].iter().rev() {
            p = dd_add(dd_mul(p, xd), Dd(c.0, c.1));
        }
        return dd_mul(xd, p).value();
    }
    dd_add_d(exp_dd(x), -1.0).value()
}

/// `ln(1 + x)`, correctly rounded. `1 + x` is formed exactly as a
/// double-double, so no information is lost for tiny `x`.
pub fn log1p(x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }
    if x < -1.0 {
        return f64::NAN;
    }
    if x == -1.0 {
        return f64::NEG_INFINITY;
    }
    if x == f64::INFINITY {
        return x;
    }
    if x == 0.0 {
        return x; /* preserve -0.0 */
    }
    if x.abs() < exp2i(-54) {
        return x;
    }
    let (h, l) = two_sum(1.0, x);
    log_dd(Dd(h, l)).value()
}

/// `sinh(x)`, correctly rounded.
pub fn sinh(x: f64) -> f64 {
    if !x.is_finite() || x == 0.0 {
        return x;
    }
    let a = x.abs();
    if a < exp2i(-27) {
        return x;
    }
    let r = if a <= 0.5 {
        /* sum over odd n of x^n/n! -- no cancellation */
        let xd = dd(a);
        let x2 = dd_mul(xd, xd);
        let mut p = Dd(INV_FACT[23].0, INV_FACT[23].1);
        let mut n: i32 = 21;
        while n >= 1 {
            let c = &INV_FACT[n as usize];
            p = dd_add(dd_mul(p, x2), Dd(c.0, c.1));
            n -= 2;
        }
        dd_mul(xd, p).value()
    } else {
        /* e^a = m*2^k, so sinh(a) = 2^(k-1) * (m - 2^(-2k)/m) */
        let (m, k) = exp_dd_scaled(a);
        let t = if k > 80 {
            Dd(0.0, 0.0)
        } else {
            dd_ldexp(dd_div(dd(1.0), m), -2 * k)
        };
        dd_ldexp(dd_sub(m, t), k - 1).value()
    };
    if x < 0.0 {
        -r
    } else {
        r
    }
}

/// `cosh(x)`, correctly rounded.
pub fn cosh(x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }
    let a = x.abs();
    if a.is_infinite() {
        return f64::INFINITY;
    }
    if a < exp2i(-27) {
        return 1.0;
    }
    /* e^a = m*2^k, so cosh(a) = 2^(k-1) * (m + 2^(-2k)/m) */
    let (m, k) = exp_dd_scaled(a);
    let t = if k > 80 {
        Dd(0.0, 0.0)
    } else {
        dd_ldexp(dd_div(dd(1.0), m), -2 * k)
    };
    dd_ldexp(dd_add(m, t), k - 1).value()
}

/// `acosh(x) = ln(x + sqrt(x*x - 1))`, correctly rounded.
pub fn acosh(x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }
    if x < 1.0 {
        return f64::NAN;
    }
    if x == 1.0 {
        return 0.0;
    }
    if x == f64::INFINITY {
        return x;
    }
    if x < 1.5 {
        /* w = 1 + t + sqrt(t*(t+2)) with t = x-1, kept in double-double so
        that the small-t cancellation of x*x - 1 never happens */
        let t = dd_add_d(dd(x), -1.0);
        let s = dd_sqrt(dd_mul(t, dd_add_d(t, 2.0)));
        return log_dd(dd_add_d(dd_add(t, s), 1.0)).value();
    }
    if x < exp2i(500) {
        let x2 = dd_mul(dd(x), dd(x));
        let s = dd_sqrt(dd_add_d(x2, -1.0));
        return log_dd(dd_add(dd(x), s)).value();
    }
    /* x*x would overflow: acosh(x) = log(x) + ln2 to full precision */
    dd_add(log_dd(dd(x)), Dd(LN2_DD.0, LN2_DD.1)).value()
}

