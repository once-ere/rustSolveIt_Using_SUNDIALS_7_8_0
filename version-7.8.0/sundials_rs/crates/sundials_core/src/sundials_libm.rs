/// C `specialcase` from musl's `exp.c`: results that overflow or underflow
/// the plain `scale*(1+tmp)` evaluation.
fn exp_specialcase(tmp: f64, sbits: u64, ki: u64) -> f64 {
    if (ki & 0x80000000) == 0 {
        /* k > 0, the exponent of scale might have overflowed by <= 460. */
        let sbits = sbits.wrapping_sub(1009u64 << 52);
        let scale = f64::from_bits(sbits);
        return f64::from_bits(0x7f00000000000000) * scale.mul_add(tmp, scale); /* 0x1p1009 */
    }
    /* k < 0, need special care in the subnormal range. */
    let sbits = sbits.wrapping_add(1022u64 << 52);
    let scale = f64::from_bits(sbits);
    let mut y = scale + scale * tmp;
    if y < 1.0 {
        /* Round y to the right precision before scaling it into the
        subnormal range, to avoid a double rounding. */
        let mut lo = scale - y + scale * tmp;
        let hi = 1.0 + y;
        lo = 1.0 - hi + y + lo;
        y = (hi + lo) - 1.0;
        if y == 0.0 {
            y = 0.0; /* avoid -0.0 with downward rounding */
        }
    }
    f64::from_bits(0x0010000000000000) * y /* 0x1p-1022 */
}

#[inline]
fn top12(x: f64) -> u32 {
    (x.to_bits() >> 52) as u32
}

/// `e^x`. Translation of musl `src/math/exp.c` (ARM optimized-routines,
/// MIT) — the algorithm and tables glibc ≥ 2.28 ships as
/// `sysdeps/ieee754/dbl-64/e_exp.c`. Worst-case error 0.51 ulp.
pub fn exp(x: f64) -> f64 {
    let mut abstop = top12(x) & 0x7ff;
    /* top12(exp2i(-54)) = 0x3c9, top12(512.0) = 0x408, top12(1024.0) = 0x409 */
    if abstop.wrapping_sub(0x3c9) >= 0x408u32.wrapping_sub(0x3c9) {
        if abstop.wrapping_sub(0x3c9) >= 0x80000000 {
            /* Avoid spurious underflow for tiny x. Note: 0 is a common input. */
            return 1.0 + x;
        }
        if abstop >= 0x409 {
            if x.to_bits() == f64::NEG_INFINITY.to_bits() {
                return 0.0;
            }
            if abstop >= 0x7ff {
                return 1.0 + x;
            }
            if x.to_bits() >> 63 != 0 {
                return 0.0; /* __math_uflow(0) */
            } else {
                return f64::INFINITY; /* __math_oflow(0) */
            }
        }
        /* Large x is special cased below. */
        abstop = 0;
    }

    /* exp(x) = 2^(k/N) * exp(r), with exp(r) in [2^(-1/2N),2^(1/2N)]. */
    let z = f64::from_bits(EXP_INVLN2N) * x;
    let shift = f64::from_bits(EXP_SHIFT);
    let mut kd = z + shift;
    let ki = kd.to_bits();
    kd -= shift;
    let r = x + kd * f64::from_bits(EXP_NEGLN2HIN) + kd * f64::from_bits(EXP_NEGLN2LON);
    /* 2^(k/N) ~= scale * (1 + tail). */
    let idx = (2 * (ki % 128)) as usize; /* EXP_TABLE_BITS = 7 */
    let top = ki << (52 - 7);
    let tail = f64::from_bits(EXP_TAB[idx]);
    let sbits = EXP_TAB[idx + 1].wrapping_add(top);
    let r2 = r * r;
    let c2 = f64::from_bits(EXP_POLY[0]);
    let c3 = f64::from_bits(EXP_POLY[1]);
    let c4 = f64::from_bits(EXP_POLY[2]);
    let c5 = f64::from_bits(EXP_POLY[3]);
    /* glibc's x86-64 `e_exp-fma.c` is built with `-mfma -mavx2
    -ffp-contract=fast`; this is the same contraction map already measured
    bit-exact for `pow` in `sundials_math.rs`. */
    let tmp = (r2 * r2).mul_add(r.mul_add(c5, c4), r2.mul_add(r.mul_add(c3, c2), tail + r));
    if abstop == 0 {
        return exp_specialcase(tmp, sbits, ki);
    }
    let scale = f64::from_bits(sbits);
    scale.mul_add(tmp, scale)
}

