/* =====================================================================
 * Double-double arithmetic
 * =====================================================================
 * Unevaluated sums `hi + lo` with `|lo| <= 0.5 * ulp(hi)`, giving about
 * 106 significant bits. The algorithms are the classical
 * Dekker/Knuth/Bailey ones; `two_prod` uses `f64::mul_add`, which Rust
 * guarantees to be a single fused multiply-add, so the product error term
 * is exact.
 */

/// An unevaluated sum `.0 + .1` carrying ~106 significant bits.
#[derive(Clone, Copy, Debug)]
pub struct Dd(pub f64, pub f64);

impl Dd {
    /// Round the double-double back to the nearest `f64`.
    #[inline]
    pub fn value(self) -> f64 {
        self.0 + self.1
    }
}

/// Knuth's `TwoSum`: exact for any finite `a`, `b`.
#[inline]
fn two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    let bb = s - a;
    let err = (a - (s - bb)) + (b - bb);
    (s, err)
}

/// Dekker's `FastTwoSum`: exact provided `|a| >= |b|`.
#[inline]
fn quick_two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    let err = b - (s - a);
    (s, err)
}

/// Exact product `a * b = p + e`, using one fused multiply-add.
#[inline]
fn two_prod(a: f64, b: f64) -> (f64, f64) {
    let p = a * b;
    let e = a.mul_add(b, -p);
    (p, e)
}

#[inline]
fn dd(hi: f64) -> Dd {
    Dd(hi, 0.0)
}

#[inline]
fn dd_neg(a: Dd) -> Dd {
    Dd(-a.0, -a.1)
}

#[inline]
fn dd_add(a: Dd, b: Dd) -> Dd {
    let (s1, e1) = two_sum(a.0, b.0);
    let (s2, e2) = two_sum(a.1, b.1);
    let (s, e) = quick_two_sum(s1, e1 + s2);
    let (s, e) = quick_two_sum(s, e + e2);
    Dd(s, e)
}

#[inline]
fn dd_sub(a: Dd, b: Dd) -> Dd {
    dd_add(a, dd_neg(b))
}

#[inline]
fn dd_add_d(a: Dd, b: f64) -> Dd {
    let (s, e) = two_sum(a.0, b);
    let (s, e) = quick_two_sum(s, e + a.1);
    Dd(s, e)
}

#[inline]
fn dd_mul(a: Dd, b: Dd) -> Dd {
    let (p, e) = two_prod(a.0, b.0);
    let e = e + (a.0 * b.1 + a.1 * b.0);
    let (s, e) = quick_two_sum(p, e);
    Dd(s, e)
}

#[inline]
fn dd_mul_d(a: Dd, b: f64) -> Dd {
    let (p, e) = two_prod(a.0, b);
    let (s, e) = quick_two_sum(p, e + a.1 * b);
    Dd(s, e)
}

/// Division by Newton refinement; three quotient digits give ~106 bits.
fn dd_div(a: Dd, b: Dd) -> Dd {
    let q1 = a.0 / b.0;
    let r = dd_sub(a, dd_mul_d(b, q1));
    let q2 = r.0 / b.0;
    let r = dd_sub(r, dd_mul_d(b, q2));
    let q3 = r.0 / b.0;
    let (s, e) = quick_two_sum(q1, q2);
    dd_add_d(Dd(s, e), q3)
}

/// Square root by one Newton step on the reciprocal square root.
fn dd_sqrt(a: Dd) -> Dd {
    if a.0 == 0.0 {
        return Dd(0.0, 0.0);
    }
    let x = 1.0 / a.0.sqrt();
    let ax = a.0 * x;
    let (p, e) = two_prod(ax, ax);
    let diff = dd_sub(a, Dd(p, e));
    let e2 = diff.0 * x * 0.5;
    let (s, e) = quick_two_sum(ax, e2);
    Dd(s, e)
}

/// Multiply by an exact power of two (no rounding).
#[inline]
fn dd_scale2(a: Dd, p: f64) -> Dd {
    Dd(a.0 * p, a.1 * p)
}

