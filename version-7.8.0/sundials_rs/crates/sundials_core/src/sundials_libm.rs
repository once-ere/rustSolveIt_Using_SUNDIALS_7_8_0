    fn sun_exp(self) -> f64;
    /// `ln(x)` — see [`log`].
    fn sun_ln(self) -> f64;
    /// `e^x - 1` — see [`expm1`].
    fn sun_exp_m1(self) -> f64;
    /// `ln(1 + x)` — see [`log1p`].
    fn sun_ln_1p(self) -> f64;
