    fn sun_sin(self) -> f64;
    /// `cos(x)` — see [`cos`].
    fn sun_cos(self) -> f64;
    /// `atan(x)` — see [`atan`].
    fn sun_atan(self) -> f64;
    /// `asin(x)` — see [`asin`].
    fn sun_asin(self) -> f64;
    /// `acos(x)` — see [`acos`].
