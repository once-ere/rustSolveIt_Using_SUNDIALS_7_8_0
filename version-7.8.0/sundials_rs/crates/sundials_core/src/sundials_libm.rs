    /* ---------------- identities that must hold to <= 2 ulp ------------- */

    fn close(a: f64, b: f64, ulps: f64) -> bool {
        if a == b {
            return true;
        }
        let u = (b.abs().max(f64::MIN_POSITIVE)) * f64::EPSILON;
        (a - b).abs() <= ulps * u
    }

    #[test]
    fn libm_identities() {
        let mut x = -3.0f64;
        while x < 3.0 {
            assert!(close(sin(x) * sin(x) + cos(x) * cos(x), 1.0, 4.0), "pythag at {x}");
            /* 1 + expm1(x) re-introduces the cancellation expm1 exists to
            avoid, so the tolerance has to absorb it. */
            assert!(
                close(exp(x), 1.0 + expm1(x), 4.0 + 4.0 / exp(x).max(f64::MIN_POSITIVE)),
                "expm1 at {x}"
            );
            if x.abs() < 1.5 {
                /* atan(tan(x)) == x for |x| < pi/2 */
                assert!(close(atan(sin(x) / cos(x)), x, 8.0), "atan(tan) at {x}");
            }
            if x > -0.9 {
                assert!(close(log1p(x), log(1.0 + x), 8.0), "log1p at {x}");
            }
            /* cosh^2 - sinh^2 cancels catastrophically: the two terms are
            each ~cosh(x)^2, so the tolerance has to grow with them. */
            let amp = cosh(x) * cosh(x);
            assert!(
                close(cosh(x) * cosh(x) - sinh(x) * sinh(x), 1.0, 8.0 * amp),
                "hyperbolic at {x}"
            );
            assert!(close(acosh(cosh(x)), x.abs(), 1e8), "acosh(cosh) at {x}");
            x += 0.0625;
        }
        let mut u = -1.0f64;
        while u <= 1.0 {
            assert!((sin(asin(u)) - u).abs() <= 8.0 * f64::EPSILON, "asin at {u}");
            /* cos(acos(u)) near u = 0 is a difference of quantities near
            pi/2, so only an absolute bound is meaningful there. */
            assert!((cos(acos(u)) - u).abs() <= 8.0 * f64::EPSILON, "acos at {u}");
            assert!(close(asin(u) + acos(u), PI_OVER_2.0, 4.0), "asin+acos at {u}");
            u += 1.0 / 64.0;
        }
        /* exact-ish anchors */
        assert!(close(sin(PI_DD.0 / 6.0), 0.5, 4.0));
        assert!(close(cos(PI_DD.0 / 3.0), 0.5, 4.0));
        assert!(close(atan(1.0), PI_OVER_4_DD.0, 1.0));
        assert!(close(log(exp(1.0)), 1.0, 2.0));
    }

    /// Huge arguments: the Payne-Hanek reduction must stay accurate where a
    /// Cody-Waite reduction would collapse.
    #[test]
    fn libm_huge_argument_reduction() {
        /* sin/cos of large powers of two must stay bounded and satisfy the
        Pythagorean identity, which they cannot if the reduction is lossy. */
        for k in 0..1000 {
            let x = (1.0f64 + (k as f64) / 512.0) * exp2i(k % 900);
            let s = sin(x);
            let c = cos(x);
            assert!(s.abs() <= 1.0 && c.abs() <= 1.0, "range at 2^{k}");
            assert!(close(s * s + c * c, 1.0, 8.0), "pythag at x = {x:e}");
        }
        /* x = 2^1023 is far beyond any Cody-Waite window */
        let x = exp2i(1023);
        assert!(close(sin(x) * sin(x) + cos(x) * cos(x), 1.0, 8.0));
    }

    /* ---------------- differential against the host libm ---------------- */

    struct Rec {
        x: f64,
        host: f64,
        cr: f64,
        resid: f64,
    }

    fn load(func: &str, corpus: &str) -> Option<Vec<Rec>> {
        let dir = std::env::var("SUNDIALS_LIBM_ORACLE_DIR").ok()?;
        let path = std::path::Path::new(&dir).join(format!("{func}_{corpus}.bin"));
        let blob = std::fs::read(&path).ok()?;
        let mut v = Vec::with_capacity(blob.len() / 32);
        for c in blob.chunks_exact(32) {
            let g = |i: usize| {
                let mut w = [0u8; 8];
                w.copy_from_slice(&c[i * 8..i * 8 + 8]);
                f64::from_bits(u64::from_le_bytes(w))
            };
            v.push(Rec { x: g(0), host: g(1), cr: g(2), resid: g(3) });
        }
        Some(v)
    }

    /// Error of `got` relative to the 113-bit value, in ulp of the
    /// correctly rounded result. `resid` carries the sub-ulp remainder the
    /// oracle measured, so this is a real number, not an integer count.
    fn ulp_error(got: f64, r: &Rec) -> Option<f64> {
        if !got.is_finite() || !r.cr.is_finite() {
            return None;
        }
        let u = {
            let n = f64::from_bits(r.cr.abs().to_bits() + 1);
            n - r.cr.abs()
        };
        if u == 0.0 || !u.is_finite() {
            return None;
        }
        Some((got - r.cr) / u - r.resid)
    }

    struct Report {
        n: usize,
        agree: usize,
        rust_max: f64,
        host_max: f64,
        first_x: f64,
    }

    fn measure(func: &str, corpus: &str, f: fn(f64) -> f64) -> Option<Report> {
        let recs = load(func, corpus)?;
        let mut rep = Report { n: 0, agree: 0, rust_max: 0.0, host_max: 0.0, first_x: f64::NAN };
        for r in &recs {
            let got = f(r.x);
            rep.n += 1;
            let same = got.to_bits() == r.host.to_bits() || (got.is_nan() && r.host.is_nan());
            if same {
                rep.agree += 1;
            } else if rep.first_x.is_nan() {
                rep.first_x = r.x;
            }
            if let Some(e) = ulp_error(got, r) {
                if e.abs() > rep.rust_max {
                    rep.rust_max = e.abs();
                }
            }
            if let Some(e) = ulp_error(r.host, r) {
                if e.abs() > rep.host_max {
                    rep.host_max = e.abs();
                }
            }
        }
        Some(rep)
    }

    fn run(func: &str, f: fn(f64) -> f64, bit_exact_expected: bool, fails: &mut Vec<String>) {
        let mut any = false;
        for corpus in ["domain", "wide"] {
            let Some(rep) = measure(func, corpus, f) else { continue };
            any = true;
            let pct = 100.0 * rep.agree as f64 / rep.n as f64;
            eprintln!(
                "{func:>6} {corpus:<6} n={:<9} rust==host {:<9} ({pct:7.4}%)  \
                 max|err| rust {:.4} ulp, host {:.4} ulp",
                rep.n, rep.agree, rep.rust_max, rep.host_max
            );
            if bit_exact_expected {
                if rep.agree != rep.n {
                    fails.push(format!(
                        "{func}/{corpus}: {} of {} inputs disagree with the host libm \
                         (first {:e})",
                        rep.n - rep.agree,
                        rep.n,
                        rep.first_x
                    ));
                }
            } else {
                /* Correct rounding is the claim for these five: the error
                against the 113-bit reference must never exceed half an ulp
                by more than the double-double residual (~2^-48 ulp). */
                if rep.rust_max > 0.5 + 1e-9 {
                    fails.push(format!(
                        "{func}/{corpus}: not correctly rounded (max {:.6} ulp)",
                        rep.rust_max
                    ));
                }
            }
        }
        if !any {
            eprintln!("{func}: differential not run (no oracle; set SUNDIALS_LIBM_ORACLE_DIR)");
        }
    }

    #[test]
    fn libm_differential_arm_lineage() {
        /* glibc >= 2.28/2.29 ships this exact ARM optimized-routines source,
        so anything short of bit-identical is a translation defect. */
        let mut fails = Vec::new();
        run("exp", exp, true, &mut fails);
        run("log", log, true, &mut fails);
        assert!(fails.is_empty(), "{}", fails.join("\n"));
    }

